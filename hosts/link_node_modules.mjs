#!/usr/bin/env node
/**
 * Links `unslop-ts/node_modules` to `hosts/node_modules` so Node.js and Bun
 * resolve bare specifiers from the engine sources.
 */

import { existsSync, rmSync, symlinkSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HOST_DIR = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = join(HOST_DIR, "..");
const HOST_MODULES = join(HOST_DIR, "node_modules");
const LINK = join(PACKAGE_ROOT, "node_modules");

function fail(code, message) {
  console.error(`${code}: ${message}`);
  process.exit(1);
}

const runtime = typeof Bun === "undefined" ? (process.versions?.node ? "node" : null) : "bun";
if (runtime === null) {
  fail("HOST_RUNTIME_MISSING", "run this script under Node.js or Bun");
}
if (!existsSync(HOST_MODULES)) {
  fail(
    "HOST_INSTALL_MISSING",
    "run npm ci --ignore-scripts or bun install --frozen-lockfile --ignore-scripts in hosts/",
  );
}
if (existsSync(LINK)) rmSync(LINK, { recursive: true, force: true });
symlinkSync(HOST_MODULES, LINK, process.platform === "win32" ? "junction" : "dir");
console.log(`linked ${LINK} -> ${HOST_MODULES} for ${runtime}`);
